// F-01 / F-03 — client and employee master data, through the same database calls the app makes.
// Includes the NF-01 regression: editing a client must not duplicate its billing lines.
// Synthetic, run-tagged data; cleaned up at the end (employee deleted, client deactivated —
// the app never deletes clients, so the tagged client stays in sandbox as inactive).
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import type { SupabaseClient } from "@supabase/supabase-js";
import { signedInClient } from "../../support/clients";
import { accountFor } from "../../support/env";
import { CleanupRegistry } from "../../support/cleanup";
import { tagged } from "../../support/run-id";

const enabled = !!accountFor("ceo_admin") && !!accountFor("coo_ops") && !!accountFor("accountant");
let ceo: SupabaseClient, coo: SupabaseClient, accountant: SupabaseClient;
const cleanup = new CleanupRegistry();
const today = new Date().toISOString().slice(0, 10);

const LINES = [
  { description: "Security Services (test)", sac_code: "998525", rate_per_month: 18000, unit_label: "Guard", sort_order: 1, is_active: true },
  { description: "Supervisor (test)", sac_code: "998525", rate_per_month: 22000, unit_label: "Supervisor", sort_order: 2, is_active: true },
];

beforeAll(async () => {
  if (!enabled) return;
  ceo = (await signedInClient("ceo_admin"))!;
  coo = (await signedInClient("coo_ops"))!;
  accountant = (await signedInClient("accountant"))!;
});

afterAll(async () => {
  if (!enabled) return;
  console.log("[cleanup]", JSON.stringify(await cleanup.run(ceo)));
  await Promise.all([ceo, coo, accountant].map((c) => c.auth.signOut()));
});

describe("F-01/F-03 client → employee workflow (API) @smoke", () => {
  it.skipIf(!enabled)("CEO creates a client with wages and billing lines, edits it, and adds an employee", async () => {
    const { data: me } = await ceo.auth.getUser();
    const clientName = tagged("Test Client");

    // 1. Client (same fields the client form sends in sandbox)
    const { data: client, error: cErr } = await ceo
      .from("clients")
      .insert({ client_name: clientName, client_code: "", service_type: "Security", client_type: "company_firm", gst_applicable: true, gst_percentage: 18, gst_type: "cgst_sgst", pf_applicable: true, esi_applicable: true, pt_applicable: true, is_active: true, is_sandbox: true, created_by: me.user!.id })
      .select("id, client_code, is_sandbox")
      .single();
    expect(cErr).toBeNull();
    cleanup.track({ table: "clients", id: client!.id, labelColumn: "client_name", undo: { kind: "update", values: { is_active: false }, reason: "clients cannot be deleted; deactivated" } });
    expect(client!.client_code, "client code generated by the database").toMatch(/\S/);
    expect(client!.is_sandbox).toBe(true);

    // 2. Wage configuration
    const { error: wErr } = await ceo.from("client_wage_config").insert({
      client_id: client!.id, designation: "S.GUARD", basic: 12000, da: 3000, ta: 0, payable_gross: 15000,
      epf_mw_wages: 15000, esi_mw_wages: 21000, effective_from: today, is_current: true, created_by: me.user!.id, is_sandbox: true,
    });
    expect(wErr).toBeNull();

    // 3. Billing lines (server-side replace, as the form does)
    const { error: l1 } = await ceo.rpc("replace_client_billing_lines", { _client_id: client!.id, _lines: LINES });
    expect(l1).toBeNull();

    // 4. Edit the client and save the same lines again — NF-01: no duplicates
    const { error: uErr } = await ceo.from("clients").update({ notes: "edited by automated test" }).eq("id", client!.id);
    expect(uErr).toBeNull();
    const { error: l2 } = await ceo.rpc("replace_client_billing_lines", { _client_id: client!.id, _lines: LINES });
    expect(l2).toBeNull();
    const { data: lines } = await ceo.from("client_billing_lines").select("description").eq("client_id", client!.id).eq("is_deleted", false);
    expect((lines ?? []).map((l) => l.description).sort(), "exactly the 2 billing lines after an edit").toEqual(LINES.map((l) => l.description).sort());

    // 5. Employee assigned to the client (same fields the employee form sends)
    const { data: emp, error: eErr } = await ceo
      .from("employees")
      .insert({ full_name: tagged("Test Employee 1"), designation: "S.GUARD", client_id: client!.id, date_of_joining: today, status: "Active", employee_code: "", basic: 12000, da: 3000, created_by: me.user!.id })
      .select("id, employee_code, is_sandbox")
      .single();
    expect(eErr).toBeNull();
    cleanup.track({ table: "employees", id: emp!.id, labelColumn: "full_name", undo: { kind: "delete" } });
    expect(emp!.employee_code, "employee code generated by the database").toMatch(/\S/);
    expect(emp!.is_sandbox, "sandbox flag on a sandbox employee").toBe(true);

    // 6. Other roles see the records according to their view permission
    const { data: cooSees } = await coo.from("employees").select("id").eq("id", emp!.id);
    expect(cooSees).toHaveLength(1);
    const { data: acctSees } = await accountant.from("clients").select("id").eq("id", client!.id);
    expect(acctSees).toHaveLength(1);
  });
});
